"use strict";

const fs = require("fs");
const path = require("path");
const http = require("http");
const { WebSocket, WebSocketServer } = require("ws");

const ROOT = path.join(__dirname, "..");
const CONFIG_PATH = process.env.ICHAT_CONFIG || path.join(ROOT, "config.json");

const DEFAULT_ROOMS = [
  "global-say",
  "global-trade",
  "global-city",
  "whisper",
  "room:general",
];

function loadConfig() {
  const defaults = {
    relayUrl: process.env.ICHAT_RELAY_URL || "ws://127.0.0.1:7711",
    httpPort: Number(process.env.ICHAT_HTTP_PORT || 7712),
    sender: process.env.ICHAT_SENDER || "Companion-Local",
    defaultRoom: process.env.ICHAT_ROOM || "global-say",
    defaultChannel: process.env.ICHAT_CHANNEL || "say",
    wowAddonPath: process.env.ICHAT_ADDON_PATH || "",
    wowSavedVariablesPath: process.env.ICHAT_SV_PATH || "",
    pollMs: Number(process.env.ICHAT_POLL_MS || 1500),
    joinRooms: DEFAULT_ROOMS,
  };
  if (fs.existsSync(CONFIG_PATH)) {
    try {
      return { ...defaults, ...JSON.parse(fs.readFileSync(CONFIG_PATH, "utf8")) };
    } catch (err) {
      console.warn("[ichat-companion] bad config.json, using defaults:", err.message);
    }
  }
  return defaults;
}

const config = loadConfig();

/** @type {Map<string, object[]>} */
const roomBuffers = new Map();
const BUFFER_LIMIT = 200;
/** @type {Set<string>} */
const seenOutboxIds = new Set();
/** @type {Set<import('ws').WebSocket>} */
const uiClients = new Set();

let relayWs = null;
let backoffMs = 1000;
let currentRoom = config.defaultRoom;
let currentChannel = config.defaultChannel;
let senderName = config.sender;

function buf(room) {
  const key = String(room || "global-say").toLowerCase();
  if (!roomBuffers.has(key)) roomBuffers.set(key, []);
  return roomBuffers.get(key);
}

function pushMsg(msg) {
  const list = buf(msg.room);
  list.push(msg);
  while (list.length > BUFFER_LIMIT) list.shift();
  const raw = JSON.stringify({ type: "msg", ...msg });
  for (const c of uiClients) {
    if (c.readyState === 1) c.send(raw);
  }
  writeInbox();
}

function luaEsc(s) {
  return String(s ?? "")
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, " ");
}

function writeInbox() {
  if (!config.wowAddonPath) return;
  const inboxPath = path.join(config.wowAddonPath, "Inbox.lua");
  try {
    fs.mkdirSync(config.wowAddonPath, { recursive: true });
    const all = [];
    for (const list of roomBuffers.values()) {
      for (const m of list) all.push(m);
    }
    all.sort((a, b) => a.ts - b.ts);
    const recent = all.slice(-100);
    const lines = recent.map((m) => {
      const parts = [
        `id="${luaEsc(m.id || "")}"`,
        `channel="${luaEsc(m.channel || "say")}"`,
        `room="${luaEsc(m.room || "")}"`,
        `sender="${luaEsc(m.sender)}"`,
        `text="${luaEsc(m.text)}"`,
        `ts=${Number(m.ts) || 0}`,
      ];
      if (m.roomName) parts.push(`roomName="${luaEsc(m.roomName)}"`);
      if (m.target) parts.push(`target="${luaEsc(m.target)}"`);
      return `  { ${parts.join(", ")} },`;
    });
    const body = [
      "-- Autogenerated by iChat companion. Data only — do not edit by hand.",
      "IChatInbox = {",
      ...lines,
      "}",
      "",
    ].join("\n");
    fs.writeFileSync(inboxPath, body, "utf8");
  } catch (err) {
    console.warn("[ichat-companion] inbox write failed:", err.message);
  }
}

function field(block, name) {
  const m = block.match(new RegExp(name + '\\s*=\\s*"([^"]*)"'));
  return m ? m[1] : undefined;
}

function fieldNum(block, name) {
  const m = block.match(new RegExp(name + "\\s*=\\s*(\\d+)"));
  return m ? Number(m[1]) : undefined;
}

function parseOutboxLua(text) {
  const items = [];
  const block =
    text.match(/outbox\s*=\s*\{([\s\S]*?)\n\s*\}/) ||
    text.match(/IChatOutbox\s*=\s*\{([\s\S]*?)\}/);
  if (!block) return items;
  const entryRe = /\{([^{}]+)\}/g;
  let m;
  while ((m = entryRe.exec(block[1]))) {
    const body = m[1];
    const id = field(body, "id");
    if (!id) continue;
    items.push({
      id,
      channel: field(body, "channel") || "say",
      room: field(body, "room"),
      roomName: field(body, "roomName"),
      target: field(body, "target"),
      text: field(body, "text") || "",
      ts: fieldNum(body, "ts") || Date.now(),
    });
  }
  return items;
}

function pollSavedVariables() {
  const sv = config.wowSavedVariablesPath;
  if (!sv || !fs.existsSync(sv)) return;
  let text;
  try {
    text = fs.readFileSync(sv, "utf8");
  } catch {
    return;
  }
  const items = parseOutboxLua(text);
  for (const item of items) {
    if (!item.id || seenOutboxIds.has(item.id)) continue;
    seenOutboxIds.add(item.id);
    ensureJoined(item.room || roomFor(item));
    sendToRelay({
      type: "msg",
      id: item.id,
      channel: item.channel,
      room: item.room || roomFor(item),
      roomName: item.roomName,
      target: item.target,
      sender: senderName,
      text: item.text,
      ts: item.ts || Date.now(),
    });
  }
  if (seenOutboxIds.size > 2000) {
    const arr = [...seenOutboxIds];
    seenOutboxIds.clear();
    for (const id of arr.slice(-500)) seenOutboxIds.add(id);
  }
}

function roomFor(item) {
  const ch = item.channel || "say";
  if (ch === "whisper") return "whisper";
  if (ch === "trade") return "global-trade";
  if (ch === "city") return "global-city";
  if (ch === "room") return "room:" + String(item.roomName || "general").toLowerCase();
  return "global-say";
}

/** @type {Set<string>} */
const joinedRooms = new Set();

function ensureJoined(room) {
  const key = String(room || "").toLowerCase();
  if (!key || joinedRooms.has(key)) return;
  joinedRooms.add(key);
  sendToRelay({ type: "join", room: key, sender: senderName });
}

function sendToRelay(obj) {
  if (!relayWs || relayWs.readyState !== 1) {
    console.warn("[ichat-companion] relay not connected; drop", obj.type);
    return false;
  }
  relayWs.send(JSON.stringify(obj));
  return true;
}

function joinDefaults() {
  const rooms = config.joinRooms || DEFAULT_ROOMS;
  for (const r of rooms) ensureJoined(r);
  ensureJoined(currentRoom);
}

function connectRelay() {
  console.log(`[ichat-companion] connecting to ${config.relayUrl}`);
  const ws = new WebSocket(config.relayUrl);
  relayWs = ws;

  ws.on("open", () => {
    backoffMs = 1000;
    console.log("[ichat-companion] relay connected");
    joinedRooms.clear();
    joinDefaults();
    broadcastUi({
      type: "status",
      connected: true,
      room: currentRoom,
      channel: currentChannel,
      sender: senderName,
    });
  });

  ws.on("message", (data) => {
    let msg;
    try {
      msg = JSON.parse(String(data));
    } catch {
      return;
    }
    if (msg.type === "msg") {
      pushMsg({
        id: msg.id,
        channel: msg.channel || "say",
        room: msg.room,
        roomName: msg.roomName,
        target: msg.target,
        sender: msg.sender,
        text: msg.text,
        ts: msg.ts,
      });
    } else if (
      msg.type === "joined" ||
      msg.type === "hello" ||
      msg.type === "presence" ||
      msg.type === "error"
    ) {
      broadcastUi(msg);
    }
  });

  ws.on("close", () => {
    console.warn(`[ichat-companion] relay closed; retry in ${backoffMs}ms`);
    broadcastUi({ type: "status", connected: false });
    scheduleReconnect();
  });

  ws.on("error", (err) => {
    console.warn("[ichat-companion] relay error:", err.message);
  });
}

function scheduleReconnect() {
  const wait = backoffMs;
  backoffMs = Math.min(backoffMs * 2, 30000);
  setTimeout(connectRelay, wait);
}

function broadcastUi(obj) {
  const raw = JSON.stringify(obj);
  for (const c of uiClients) {
    if (c.readyState === 1) c.send(raw);
  }
}

function serveStatic(req, res) {
  const url = new URL(req.url, "http://127.0.0.1");
  if (url.pathname === "/api/health") {
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(
      JSON.stringify({
        ok: true,
        connected: !!(relayWs && relayWs.readyState === 1),
        room: currentRoom,
        channel: currentChannel,
        sender: senderName,
        addonPath: config.wowAddonPath || null,
        savedVariablesPath: config.wowSavedVariablesPath || null,
        stage: 1,
        note: "Primary UX is in-game GlobalChat; this UI is a realtime fallback.",
      })
    );
    return;
  }

  if (url.pathname === "/api/history") {
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify(buf(currentRoom)));
    return;
  }

  let file = url.pathname === "/" ? "/index.html" : url.pathname;
  file = path.normalize(file).replace(/^(\.\.[/\\])+/, "");
  const full = path.join(ROOT, "public", file);
  if (!full.startsWith(path.join(ROOT, "public"))) {
    res.writeHead(403);
    res.end("Forbidden");
    return;
  }
  fs.readFile(full, (err, data) => {
    if (err) {
      res.writeHead(404);
      res.end("Not found");
      return;
    }
    const ext = path.extname(full);
    const types = {
      ".html": "text/html; charset=utf-8",
      ".js": "text/javascript; charset=utf-8",
      ".css": "text/css; charset=utf-8",
    };
    res.writeHead(200, { "Content-Type": types[ext] || "application/octet-stream" });
    res.end(data);
  });
}

const httpServer = http.createServer(serveStatic);
const uiWss = new WebSocketServer({ server: httpServer });

uiWss.on("connection", (ws) => {
  uiClients.add(ws);
  ws.send(
    JSON.stringify({
      type: "status",
      connected: !!(relayWs && relayWs.readyState === 1),
      room: currentRoom,
      channel: currentChannel,
      sender: senderName,
    })
  );
  for (const m of buf(currentRoom)) {
    ws.send(JSON.stringify({ type: "msg", ...m }));
  }

  ws.on("message", (data) => {
    let msg;
    try {
      msg = JSON.parse(String(data));
    } catch {
      return;
    }
    if (msg.type === "join") {
      currentRoom = String(msg.room || currentRoom).slice(0, 96);
      currentChannel = String(msg.channel || currentChannel).slice(0, 32);
      if (msg.sender) senderName = String(msg.sender).slice(0, 64);
      ensureJoined(currentRoom);
      broadcastUi({
        type: "status",
        connected: true,
        room: currentRoom,
        channel: currentChannel,
        sender: senderName,
      });
      return;
    }
    if (msg.type === "msg") {
      const text = String(msg.text || "").slice(0, 500);
      if (!text.trim()) return;
      const channel = String(msg.channel || currentChannel || "say");
      const room = msg.room || roomFor({ channel, roomName: msg.roomName });
      ensureJoined(room);
      sendToRelay({
        type: "msg",
        channel,
        room,
        roomName: msg.roomName,
        target: msg.target,
        sender: msg.sender || senderName,
        text,
        ts: Date.now(),
      });
    }
  });

  ws.on("close", () => uiClients.delete(ws));
});

httpServer.listen(config.httpPort, "127.0.0.1", () => {
  console.log(`[ichat-companion] local fallback UI http://127.0.0.1:${config.httpPort}`);
  console.log("[ichat-companion] Stage 1 primary UX = in-game GlobalChat channels");
  if (!config.wowAddonPath) {
    console.log("[ichat-companion] wowAddonPath empty — no Inbox.lua writes");
  }
  if (!config.wowSavedVariablesPath) {
    console.log("[ichat-companion] wowSavedVariablesPath empty — not polling outbox");
  }
});

connectRelay();
setInterval(pollSavedVariables, config.pollMs);

process.on("SIGINT", () => process.exit(0));
